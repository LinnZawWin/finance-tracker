"""Generate Bank Statement Lines for cash, which has no bank statement. See "Cash lines" in CLAUDE.md.

    python scripts/cash_lines.py            dry run: what would be created, updated or removed
    python scripts/cash_lines.py --apply    write (reconcile.py runs this first, under the lock)

Cash accounts are the Bank Accounts named "Cash" (AUD) and "<CUR> Cash" (foreign cash, for example "CNY Cash").
- Statements: one "Cash" statement for AUD cash; one "<account> - <project>" statement per project for foreign
  cash ("<account> - No project" when the transaction has none). No period, no balances, Source Type Other.
- One line per active cash Finance Transaction (Paid From or Transfer To a cash account), Bank Reference
  "FT-<transaction id>", Source Generated, AUD like the transaction (foreign cash: Original Amount / Currency
  from the transaction). Expense: -Amount, Income: +Amount, Transfer out of cash: -, into cash: +.
  A split cash bill whose Notes start with the bill total ("76.35 - ...") gets the total, the cash that left.
  Expense and Income lines are matched to their transaction (Method Manual, Confirmed); the transaction is then
  Reconciled when its Reconciliation Difference is 0. Transfer lines are Status Transfer, not matched (the
  other side is already a bank line), with Transfer Counterpart when that side has exactly one line.
- Cash withdrawals and deposits on bank lines (ANZ ATM, NON-ANZ ATM, ... WITHDRAWAL, CASH DEPOSIT): a cash line
  with the opposite amount, Bank Reference "BL-<bank line id>", and both lines paired as Status Transfer.
- A transaction that changed updates its line and match; one that was deleted or deactivated loses its line.
"""
import datetime as dt
import re
import sys

import dv
import statement_compare as sc
from recalc import rollup

O = sc.O
GENERATED, OTHER = O + 3, O + 3
UNMATCHED, MATCHED, TRANSFER = O, O + 2, O + 3
PARTREC, RECONCILED = O + 1, O + 2
EXPENSE, INCOME, XFER = O, O + 1, O + 2
MANUAL, CONFIRMED = O + 3, O + 1
WITHDRAWAL = re.compile(r"^(NON-ANZ ATM|ANZ ATM)\b|\bATM WITHDRAWAL|\bCASH WITHDRAWAL|\bPOST WITHDRAWAL", re.I)
DEPOSIT = re.compile(r"\bCASH DEPOSIT|\bATM DEPOSIT|\bPOST DEPOSIT", re.I)
TOTAL = re.compile(r"^\s*(\d[\d,]*(?:\.\d+)?)\s*[-−]")
NOTE = "Generated by cash_lines.py from the Finance Transactions and cash withdrawals; no period or balances."
cents = lambda v: round(float(v or 0) * 100)


def local_day(s):
    return (dt.datetime.fromisoformat(s.replace("Z", "+00:00")) + dt.timedelta(hours=10)).date().isoformat()


def run(apply, verbose=False):
    accts = dv.get_all("lzw_bankaccounts?$select=lzw_name,_lzw_accountcurrency_value")
    name = {a["lzw_bankaccountid"]: a["lzw_name"] for a in accts}
    cash = {a["lzw_bankaccountid"]: a for a in accts if a["lzw_name"] == "Cash" or a["lzw_name"].endswith(" Cash")}
    if not cash:
        return
    aud = sc.currency_id("AUD")
    proj = {p["lzw_financeprojectid"]: p["lzw_name"] for p in dv.get_all("lzw_financeprojects?$select=lzw_name")}
    stmts = {(s["_lzw_bankaccount_value"], s["lzw_name"]): s["lzw_bankstatementid"] for c in cash for s in dv.get_all(
        f"lzw_bankstatements?$select=lzw_name,_lzw_bankaccount_value&$filter=_lzw_bankaccount_value eq {c}")}
    existing = {}
    for c in cash:
        for l in dv.get_all("lzw_bankstatementlines?$select=lzw_name,lzw_transactiondate,lzw_amount,lzw_bankreference,"
                            "lzw_originalamount,lzw_status,_lzw_bankstatement_value,_lzw_transfercounterpart_value"
                            f"&$filter=_lzw_bankaccount_value eq {c} and lzw_source eq {GENERATED}"):
            existing[l["lzw_bankreference"]] = l
    flt = " or ".join(f"_lzw_paidfrom_value eq {c} or _lzw_transferto_value eq {c}" for c in cash)
    fts = dv.get_all("lzw_financetransactions?$select=lzw_name,lzw_payee,lzw_transactiondate,lzw_type,lzw_amount,"
                     "lzw_originalamount,lzw_notes,_lzw_paidfrom_value,_lzw_transferto_value,_lzw_project_value,"
                     f"statecode&$filter=statecode eq 0 and ({flt})")

    def statement(acc_id, project_id):
        sname = "Cash" if cash[acc_id]["lzw_name"] == "Cash" else \
            f"{cash[acc_id]['lzw_name']} - {proj.get(project_id, 'No project')}"
        key = (acc_id, sname)
        if key not in stmts:
            print(f"  + statement {sname}")
            stmts[key] = None
            if apply:
                _, h = dv.call("POST", "lzw_bankstatements", {
                    "lzw_name": sname, "lzw_sourcetype": OTHER, "lzw_notes": NOTE,
                    "lzw_BankAccount@odata.bind": f"/lzw_bankaccounts({acc_id})",
                    "transactioncurrencyid@odata.bind": f"/transactioncurrencies({aud})"})
                stmts[key] = h.get("OData-EntityId", h.get("odata-entityid")).rsplit("(", 1)[1].rstrip(")")
        return stmts[key]

    wanted = {}  # bank reference -> dict(line, account, statement, ft, counterpart)
    for t in fts:
        for side, acc_id in (("from", t["_lzw_paidfrom_value"]), ("to", t["_lzw_transferto_value"])):
            if acc_id not in cash or (side == "to" and t["lzw_type"] != XFER):
                continue
            amt = cents(t["lzw_amount"])
            m = TOTAL.match(t["lzw_notes"] or "")
            if t["lzw_type"] == EXPENSE and m and cents(m[1].replace(",", "")) > amt:
                amt = cents(m[1].replace(",", ""))  # split cash bill: the whole bill left the cash
            amount = (amt if t["lzw_type"] == INCOME or side == "to" else -amt) / 100
            line = {"date": local_day(t["lzw_transactiondate"]), "amount": amount,
                    "description": t["lzw_name"], "merchant": t["lzw_payee"],
                    "bank_reference": f"FT-{t['lzw_financetransactionid']}"[:100]}
            cur = cash[acc_id]["_lzw_accountcurrency_value"]
            if cash[acc_id]["lzw_name"] != "Cash" and t["lzw_originalamount"] is not None:
                line["original_amount"] = t["lzw_originalamount"]
                line["original_currency_id"] = cur
            ref = line["bank_reference"] + ("-in" if side == "to" and t["_lzw_paidfrom_value"] in cash else "")
            line["bank_reference"] = ref
            wanted[ref] = dict(line=line, acc=acc_id, project=t["_lzw_project_value"], ft=t,
                               transfer=t["lzw_type"] == XFER)
    aud_cash = next((c for c, a in cash.items() if a["lzw_name"] == "Cash"), None)
    if aud_cash:
        for l in dv.get_all("lzw_bankstatementlines?$select=lzw_name,lzw_transactiondate,lzw_amount,"
                            "_lzw_bankaccount_value,lzw_status&$filter=statecode eq 0 and lzw_source ne "
                            f"{GENERATED} and (contains(lzw_name,'ATM') or contains(lzw_name,'WITHDRAWAL') or "
                            "contains(lzw_name,'DEPOSIT'))"):
            d = l["lzw_name"] or ""
            if l["_lzw_bankaccount_value"] in cash or not ((WITHDRAWAL.search(d) and l["lzw_amount"] < 0)
                                                          or (DEPOSIT.search(d) and l["lzw_amount"] > 0)):
                continue
            ref = f"BL-{l['lzw_bankstatementlineid']}"
            kind = "Cash withdrawal" if l["lzw_amount"] < 0 else "Cash deposit"
            wanted[ref] = dict(line={"date": l["lzw_transactiondate"], "amount": -l["lzw_amount"],
                                     "description": re.sub(r"\s+", " ", f"{kind}: {d}").strip()[:500], "bank_reference": ref},
                               acc=aud_cash, project=None, ft=None, transfer=True, bank_line=l)

    made = updated = removed = 0
    now = dt.datetime.now(dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    touched_fts = set()
    for ref, w in sorted(wanted.items(), key=lambda kv: kv[1]["line"]["date"]):
        l, old = w["line"], existing.get(ref)
        same = old and cents(old["lzw_amount"]) == cents(l["amount"]) and old["lzw_transactiondate"] == l["date"] \
            and old["lzw_name"] == l["description"][:500] and (old["lzw_status"] == TRANSFER) == w["transfer"]
        if same:  # a change of Type (Transfer to Income or Expense, or back) also needs an update
            continue
        sid = statement(w["acc"], w["project"])
        verb = "update" if old else "create"
        print(f"  {verb} {cash[w['acc']]['lzw_name']:9} {l['date']} {l['amount']:>9.2f}  {l['description'][:60]}")
        if not apply:
            continue
        body = sc.line_body(l, w["acc"], sid, "Generated", aud)
        if l.get("original_currency_id"):
            body["lzw_OriginalCurrency@odata.bind"] = f"/transactioncurrencies({l['original_currency_id']})"
        if old:
            lid = old["lzw_bankstatementlineid"]
            dv.patch(f"lzw_bankstatementlines({lid})", body)
            updated += 1
        else:
            key = body["lzw_duplicatekey"].replace("'", "''")
            q = f"lzw_bankstatementlines?$select=lzw_bankstatementlineid&$filter=lzw_bankreference eq '{ref}'"
            dv.post("lzw_bankstatementlines", body, done=lambda: bool(dv.get(q)["value"]))
            lid = dv.get(q)["value"][0]["lzw_bankstatementlineid"]
            made += 1
        if w["transfer"]:
            other = w.get("bank_line")
            if other is None:  # a Transfer transaction: its bank side, when it has exactly one line
                ms = dv.get("lzw_reconciliationmatchs?$select=_lzw_bankstatementline_value&$filter="
                            f"_lzw_financetransaction_value eq {w['ft']['lzw_financetransactionid']}")["value"]
                other = {"lzw_bankstatementlineid": ms[0]["_lzw_bankstatementline_value"]} if len(ms) == 1 else None
            pb = {"lzw_status": TRANSFER}
            if other:
                pb["lzw_TransferCounterpart@odata.bind"] = f"/lzw_bankstatementlines({other['lzw_bankstatementlineid']})"
                if w.get("bank_line"):
                    dv.patch(f"lzw_bankstatementlines({other['lzw_bankstatementlineid']})", {
                        "lzw_status": TRANSFER, "lzw_TransferCounterpart@odata.bind": f"/lzw_bankstatementlines({lid})"})
            dv.patch(f"lzw_bankstatementlines({lid})", pb)
            continue
        tid = w["ft"]["lzw_financetransactionid"]
        ms = dv.get("lzw_reconciliationmatchs?$select=lzw_reconciliationmatchid&$filter="
                    f"_lzw_bankstatementline_value eq {lid} and _lzw_financetransaction_value eq {tid}")["value"]
        if ms:
            dv.patch(f"lzw_reconciliationmatchs({ms[0]['lzw_reconciliationmatchid']})", {"lzw_allocatedamount": l["amount"]})
        else:
            mq = (f"lzw_reconciliationmatchs?$select=lzw_reconciliationmatchid&$filter=_lzw_bankstatementline_value"
                  f" eq {lid} and _lzw_financetransaction_value eq {tid}")
            dv.post("lzw_reconciliationmatchs", {
                "lzw_BankStatementLine@odata.bind": f"/lzw_bankstatementlines({lid})",
                "lzw_FinanceTransaction@odata.bind": f"/lzw_financetransactions({tid})",
                "lzw_allocatedamount": l["amount"], "lzw_matchmethod": MANUAL, "lzw_matchstatus": CONFIRMED,
                "lzw_confirmedon": now, "lzw_confidence": 1, "lzw_aireasoning": "cash_lines.py: generated cash line",
                "transactioncurrencyid@odata.bind": f"/transactioncurrencies({aud})"}, done=lambda: bool(dv.get(mq)["value"]))
        dv.patch(f"lzw_bankstatementlines({lid})", {"lzw_status": MATCHED})
        rollup("lzw_bankstatementlines", lid, "lzw_allocatedamount")
        touched_fts.add(tid)
    for ref, old in existing.items():
        if ref in wanted:
            continue
        print(f"  remove    {old['lzw_transactiondate']} {old['lzw_amount']:>9.2f}  {old['lzw_name'][:60]}")
        if not apply:
            continue
        lid = old["lzw_bankstatementlineid"]
        for m in dv.get("lzw_reconciliationmatchs?$select=lzw_reconciliationmatchid,_lzw_financetransaction_value"
                        f"&$filter=_lzw_bankstatementline_value eq {lid}")["value"]:
            dv.call("DELETE", f"lzw_reconciliationmatchs({m['lzw_reconciliationmatchid']})")
            touched_fts.add(m["_lzw_financetransaction_value"])
        if old["_lzw_transfercounterpart_value"]:
            cp = old["_lzw_transfercounterpart_value"]
            dv.call("DELETE", f"lzw_bankstatementlines({cp})/lzw_TransferCounterpart/$ref")
            dv.patch(f"lzw_bankstatementlines({cp})", {"lzw_status": UNMATCHED})
        dv.call("DELETE", f"lzw_bankstatementlines({lid})")
        removed += 1
    for tid in touched_fts:
        if not dv.get(f"lzw_financetransactions?$select=lzw_financetransactionid&$filter=lzw_financetransactionid eq {tid}")["value"]:
            continue
        rollup("lzw_financetransactions", tid, "lzw_actualamount")
        diff = dv.get(f"lzw_financetransactions({tid})?$select=lzw_reconciliationdifference")["lzw_reconciliationdifference"]
        dv.patch(f"lzw_financetransactions({tid})", {"lzw_reconciliationstatus": RECONCILED if cents(diff) == 0 else PARTREC})
    if apply and (made or removed):
        for sid in stmts.values():
            if sid:
                rollup("lzw_bankstatements", sid, "lzw_linecount")
    print(f"Cash lines: {len(wanted)} wanted, {made} created, {updated} updated, {removed} removed"
          + ("" if apply else " (dry run)"))


if __name__ == "__main__":
    run("--apply" in sys.argv, "--verbose" in sys.argv)
