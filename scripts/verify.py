"""Phase 3: confirm that every table, column, relationship, view, the app and the flow exist in the
solution. With --write-docs it also regenerates docs/schema.md from the live metadata."""
import os
import sys

import build_ui
import dv
import spec

FORMULAS = {(spec.table_logical(t), spec.logical(c["name"])): c["formula"]
            for t in spec.TABLES for c in t["columns"] if c["kind"] == "calc"}
EXPECT = {"string": "String", "memo": "Memo", "bool": "Boolean", "choice": "Picklist", "gchoice": "Picklist",
          "date": "DateTime", "datetime": "DateTime", "money": "Money", "decimal": "Decimal", "int": "Integer",
          "file": "File", "image": "Image", "lookup": "Lookup", "calc": "Decimal"}
problems, ok = [], 0


def check(cond, msg):
    global ok
    if cond:
        ok += 1
    else:
        problems.append(msg)
        print("  MISSING/WRONG:", msg)


def type_name(a):
    t = a.get("AttributeTypeName", {}).get("Value", a["AttributeType"])
    return t.replace("Type", "")


def describe(a, col):
    k = col["kind"]
    if k == "string":
        return f"Text ({col['length']})"
    if k == "memo":
        return "Multiline text"
    if k == "bool":
        return f"Yes/No (default {'Yes' if col['default'] else 'No'})"
    if k == "choice":
        d = f"; default {col['default']}" if col["default"] else ""
        return "Choice: " + ", ".join(f"{o} ({spec.OPT + i})" for i, o in enumerate(col["options"])) + d
    if k == "gchoice":
        d = f"; default {col['default']}" if col["default"] else ""
        return "Global choice lzw_sharetype" + d
    if k == "date":
        return "Date Only"
    if k == "datetime":
        return "Date and time (user local)"
    if k == "money":
        return "Currency, precision 2, " + ("signed" if col["signed"] else "0 or more")
    if k == "decimal":
        return f"Decimal, {col.get('places', 2)} places, {col['lo']} to {col['hi']}"
    if k == "int":
        return "Whole number"
    if k == "file":
        return "File"
    if k == "image":
        return "Image (primary image)"
    if k == "lookup":
        return f"Lookup to {col['target']}, Restrict delete"
    if k == "rollup":
        attr, op, val = col["flt"]
        what = "count of rows" if col["agg"] == "Count" else f"sum of {col['source']}"
        cond = "active rows" if attr == "statecode" else f"{attr} {'=' if op == 'Equal' else 'is not'} {val}"
        return f"Rollup ({'whole number' if col['type'] == 'int' else 'currency'}): {what} in {col['child']} where {cond}"
    return "Formula (Power Fx), decimal, 2 places"


def main():
    sol = dv.get(f"solutions?$select=solutionid,friendlyname,version,ismanaged&$expand=publisherid($select=uniquename,"
                 f"customizationprefix)&$filter=uniquename eq '{dv.SOLUTION}'")["value"]
    check(bool(sol), "solution")
    s = sol[0]
    check(s["friendlyname"] == "Finance Tracker" and s["version"] == "1.0.0.0" and not s["ismanaged"]
          and s["publisherid"]["customizationprefix"] == "lzw", "solution properties")
    comps = dv.get_all(f"solutioncomponents?$select=objectid,componenttype,rootcomponentbehavior&$filter=_solutionid_value eq {s['solutionid']}")
    in_sol = {c["objectid"].lower(): c for c in comps}
    by_type = {}
    for c in comps:
        by_type[c["componenttype"]] = by_type.get(c["componenttype"], 0) + 1
    print("solution component counts by type:", dict(sorted(by_type.items())))

    doc = ["# Finance Tracker schema (as built)", "",
           "Generated by `python scripts/verify.py --write-docs` from the live Dataverse metadata.", "",
           f"- Solution: `{dv.SOLUTION}` (unmanaged, version 1.0.0.0, publisher prefix `lzw`)",
           f"- Option values start at {spec.OPT}.",
           "- All tables are user-owned. All lookups are 1:N with Restrict delete and no cascades.",
           "- Every table with a currency column also has the system columns `transactioncurrencyid`, `exchangerate` "
           "and a `_base` companion per currency column.", "",
           "## Global choice", "", "`lzw_sharetype` (Share Type): "
           + ", ".join(f"{o} ({spec.OPT + i})" for i, o in enumerate(spec.SHARE_TYPE)) + ". Default on Finance "
           "Transaction: Mine.", ""]
    g = dv.get("GlobalOptionSetDefinitions(Name='lzw_sharetype')")
    check(g["MetadataId"].lower() in in_sol, "global choice lzw_sharetype in solution")
    labels = [o["Label"]["UserLocalizedLabel"]["Label"] for o in g["Options"]]
    check(labels == spec.SHARE_TYPE, f"lzw_sharetype options {labels}")

    doc += ["## Tables", ""]
    full_tables = set()
    for t in spec.TABLES:
        tl = spec.table_logical(t)
        e = dv.get(f"EntityDefinitions(LogicalName='{tl}')?$select=MetadataId,OwnershipType,EntitySetName,PrimaryNameAttribute")
        check(e["MetadataId"].lower() in in_sol and in_sol[e["MetadataId"].lower()]["rootcomponentbehavior"] == 0,
              f"table {tl} in solution with all components")
        full_tables.add(tl)
        check(e["OwnershipType"] == "UserOwned", f"{tl} user-owned")
        attrs = {a["LogicalName"]: a for a in dv.get_all(
            f"EntityDefinitions(LogicalName='{tl}')/Attributes?$select=LogicalName,AttributeType,AttributeTypeName,SchemaName,RequiredLevel")}
        rels = {r["ReferencingAttribute"]: r for r in dv.get(
            f"EntityDefinitions(LogicalName='{tl}')/ManyToOneRelationships?$select=SchemaName,ReferencingAttribute,"
            "ReferencedEntity,CascadeConfiguration")["value"]}
        prim = t["primary"] + (f", autonumber {t['autonumber']}" if t.get("autonumber") else f", text {t.get('primary_len', 200)}")
        doc += [f"### {t['display']} (`{tl}`)", "", f"Entity set: `{e['EntitySetName']}`. Primary column: `lzw_name` ({prim}).", "",
                "| Display name | Logical name | Type | Required |", "|---|---|---|---|"]
        for col in t["columns"]:
            cl = spec.logical(col["name"], col.get("schema"))
            a = attrs.get(cl)
            check(a is not None, f"column {tl}.{cl}")
            if not a:
                continue
            want = "Integer" if col.get("type") == "int" else "Money" if col["kind"] == "rollup" else EXPECT[col["kind"]]
            check(type_name(a) == want or a["AttributeType"] == want, f"{tl}.{cl} type {type_name(a)} (expected {want})")
            if col["kind"] == "lookup":
                r = rels.get(cl)
                check(r is not None and r["ReferencedEntity"] == col["target"]
                      and r["CascadeConfiguration"]["Delete"] == "Restrict", f"relationship for {tl}.{cl}")
                desc = describe(a, col) + (f" (relationship `{r['SchemaName']}`, navigation property `{a['SchemaName']}`)" if r else "")
            else:
                desc = describe(a, col)
            if col["kind"] in ("rollup", "calc"):
                d = dv.get(f"EntityDefinitions(LogicalName='{tl}')/Attributes(LogicalName='{cl}')/Microsoft.Dynamics.CRM."
                           f"{want}AttributeMetadata?$select=SourceType")
                check(d["SourceType"] == (2 if col["kind"] == "rollup" else 3), f"{tl}.{cl} source type {d['SourceType']}")
            req = "Yes" if a["RequiredLevel"]["Value"] == "ApplicationRequired" else ""
            check(bool(req) == bool(col.get("required")), f"{tl}.{cl} required level")
            doc.append(f"| {col['name']} | `{cl}` | {desc} | {req} |")
        doc.append("")

    acc = dv.get("EntityDefinitions(LogicalName='account')/Attributes(LogicalName='lzw_isbank')?$select=MetadataId,AttributeType")
    check(acc["AttributeType"] == "Boolean" and acc["MetadataId"].lower() in in_sol, "account.lzw_isbank in solution")
    doc += ["### Account (existing table)", "", "| Display name | Logical name | Type |", "|---|---|---|",
            "| Is Bank | `lzw_isbank` | Yes/No (default No) |", "",
            "Public view **Banks** (Is Bank = Yes, active). It is the only lookup view for Bank Account.Bank. "
            "No Account form was changed.", ""]

    doc += ["## Formula columns", "",
            "Power Fx formula columns (Decimal, 2 places), created by `build_formulas.py`. A formula column cannot be "
            "Currency, so they show no currency symbol. An empty input counts as 0.", "",
            "| Table | Column | Formula |", "|---|---|---|"]
    doc += [f"| `{t}` | `{c}` | `{f}` |" for (t, c), f in FORMULAS.items()]
    doc += ["", "## Rollup notes", "",
            "- Rollups refresh on the hourly system job, with the Recalculate button on the form, or with `scripts/recalc.py`.",
            "- Line Count counts active Bank Statement Lines only.", ""]

    doc += ["## Views", "", "| Table | View | Filter |", "|---|---|---|"]
    notes = {"Needs Details": "Needs Details = Yes", "Unreconciled": "Reconciliation Status = Unreconciled",
             "Last 30 Days": "Transaction Date in the last 30 days", "By Project": "Project has a value, sorted by Project",
             "Unmatched Lines": "Status = Unmatched or Partly Matched", "Pending Lines": "Is Pending = Yes",
             "Transfers": "Status = Transfer", "Proposed Matches": "Match Status = Proposed (editable grid)",
             "Confirmed Matches": "Match Status = Confirmed", "Owned Assets": "Status = Owned",
             "Sold Assets": "Status = Sold", "Banks": "Is Bank = Yes"}
    view_ids = {}
    for table, views in build_ui.VIEWS.items():
        for name, *_ in views:
            v = dv.get(f"savedqueries?$select=savedqueryid&$filter=returnedtypecode eq '{table}' and name eq '{name}' and querytype eq 0")["value"]
            # A view of a table that is in the solution with all its components travels with that table.
            check(bool(v) and (v[0]["savedqueryid"].lower() in in_sol or table in full_tables),
                  f"view {table}: {name} in solution")
            if v:
                view_ids[(table, name)] = v[0]["savedqueryid"]
            doc.append(f"| `{table}` | {name} | {notes[name]} (active rows) |")
    doc += ["", "Each table's default \"Active ...\" view was given useful columns and is used by the form subgrids.", ""]

    for table in build_ui.FORMS:
        f = dv.get(f"systemforms?$select=formid,formxml&$filter=objecttypecode eq '{table}' and type eq 2")["value"][0]
        for tab in build_ui.FORMS[table]:
            for sec in tab[1]:
                if sec[0] == "subgrid":
                    check(sec[3] in f["formxml"], f"form {table}: subgrid {sec[3]}")
    bank_form = dv.get("systemforms?$select=formxml&$filter=objecttypecode eq 'lzw_bankaccount' and type eq 2")["value"][0]["formxml"]
    check(view_ids.get(("account", "Banks"), "x").upper() in bank_form.upper(), "Banks lookup view on Bank Account.Bank")
    grid = dv.get("customcontroldefaultconfigs?$select=controldescriptionxml&$filter=primaryentitytypecode eq 'lzw_reconciliationmatch'")["value"]
    check(bool(grid) and '<EnableEditing static="true" type="Enum">yes' in (grid[0]["controldescriptionxml"] or ""),
          "editable grid on Reconciliation Match")

    apps = [a for a in dv.get("appmodules?$select=appmoduleid,uniquename,name,statecode,publishedon")["value"]
            if a["uniquename"] == "lzw_FinanceTracker"]
    check(bool(apps) and apps[0]["appmoduleid"].lower() in in_sol, "app lzw_FinanceTracker published and in solution")
    sm = dv.get("sitemaps?$select=sitemapid,sitemapxml&$filter=sitemapnameunique eq 'lzw_FinanceTracker'")["value"]
    check(bool(sm) and sm[0]["sitemapid"].lower() in in_sol, "site map in solution")
    for title, items in build_ui.SITEMAP:
        check(f'Title="{title}"' in sm[0]["sitemapxml"], f"site map group {title}")
        for it in items:
            check(('Title="Banks"' if it == "BANKS" else f'Entity="{it}"') in sm[0]["sitemapxml"], f"site map item {it}")

    # The Keep flow was deleted on 2026-11-20 (the web page replaced the Keep Inbox sheet).
    fl = dv.get("workflows?$select=workflowid&$filter=category eq 5 and name eq 'Finance Tracker - Import Keep Rows'")["value"]
    check(not fl, "Keep flow is deleted")
    fl = dv.get("workflows?$select=workflowid,statecode,clientdata&$filter=category eq 5 and "
                "name eq 'Scheduled: Create Finance Transactions from Planned Transactions'")["value"]
    check(bool(fl) and fl[0]["workflowid"].lower() in in_sol, "Planned Transactions flow in solution")
    check(bool(fl) and fl[0]["statecode"] == 1, "Planned Transactions flow is ON")
    check(bool(fl) and "lzw_FinanceTrackerDataverse" in fl[0]["clientdata"],
          "Planned Transactions flow uses the Dataverse connection reference")
    ev = dv.get("environmentvariabledefinitions?$select=environmentvariabledefinitionid,defaultvalue&$filter=schemaname eq 'lzw_KeepInboxSheetId'")["value"]
    check(bool(ev) and ev[0]["environmentvariabledefinitionid"].lower() in in_sol and not ev[0].get("defaultvalue"),
          "environment variable lzw_KeepInboxSheetId (empty) in solution")
    ev = dv.get("environmentvariabledefinitions?$select=environmentvariabledefinitionid&$filter=schemaname eq 'lzw_ReconcileLock'")["value"]
    check(bool(ev) and ev[0]["environmentvariabledefinitionid"].lower() in in_sol,
          "environment variable lzw_ReconcileLock (reconciliation lock) in solution")
    for cr in ("lzw_FinanceTrackerDataverse", "lzw_FinanceTrackerGoogleSheets"):
        r = dv.get(f"connectionreferences?$select=connectionreferenceid&$filter=connectionreferencelogicalname eq '{cr}'")["value"]
        check(bool(r) and r[0]["connectionreferenceid"].lower() in in_sol, f"connection reference {cr} in solution")

    counts = {"accounts?$filter=lzw_isbank eq true": 3, "lzw_bankaccounts": 5, "lzw_financecategories": 22, "lzw_financeprojects": 1}
    for q, n in counts.items():
        got = len(dv.get_all(q + ("&" if "?" in q else "?") + "$select=createdon"))
        check(got >= n, f"seed rows {q}: {got} (expected at least {n})")

    doc += ["## Other solution components", "",
            "- Model-driven app `lzw_FinanceTracker` (Finance Tracker) with site map groups Capture, Reconcile, "
            "Statements, Assets and Setup. Setup > Banks opens Account with the Banks view.",
            "- Power Apps grid control with editing enabled as the default grid for `lzw_reconciliationmatch` "
            "(applies to all of its views, so Match Status can be changed inline in Proposed Matches).",
            "- Cloud flow \"Scheduled: Create Finance Transactions from Planned Transactions\" (on). The Keep "
            "flow \"Finance Tracker - Import Keep Rows\" was deleted on 2026-11-20.",
            "- Environment variable `lzw_KeepInboxSheetId` (text, no value).",
            "- Connection references `lzw_FinanceTrackerDataverse` (Microsoft Dataverse) and "
            "`lzw_FinanceTrackerGoogleSheets` (Google Sheets, standard connector).",
            "- The platform added `transactioncurrency` and `account` to the solution as references only "
            "(no changes to Currency).", ""]
    print(f"\n{ok} checks passed, {len(problems)} problems")
    if "--write-docs" in sys.argv:
        path = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "docs", "schema.md")
        os.makedirs(os.path.dirname(path), exist_ok=True)
        open(path, "w").write("\n".join(doc) + "\n")
        print("wrote", path)
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
